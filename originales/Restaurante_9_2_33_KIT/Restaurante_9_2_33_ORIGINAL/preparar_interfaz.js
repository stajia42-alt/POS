'use strict';
// Build the UI into a JS module so the executable does not depend on static assets.
const fs=require('fs');
const path=require('path');
const sources={activar:'activar_celular.html',extra:'public/extra.js',inicio:'public/index.html',estilo:'public/style.css',cliente:'public/app.js',configuracion:'configuracion.html',menu:'public/menu.html',menuEstilo:'public/menu.css',menuCliente:'public/menu.js',menuProyecto:'public/menu-proyecto.js',menuSql:'public/menu-sql.js',menuVisual:'public/menu-visual.js',menuVisualLogica:'public/menu-visual-logica.js'};
const content={};
for(const [key,file] of Object.entries(sources)) {
  content[key]=fs.readFileSync(path.join(__dirname,file),'utf8');
  if(key==='menuCliente')content[key]=fs.readFileSync(path.join(__dirname,'public/menu-consolidar.js'),'utf8')+'\n'+fs.readFileSync(path.join(__dirname,'public/menu-imagen.js'),'utf8')+'\n'+content[key];
  if(!content[key].trim())throw new Error('Archivo de interfaz vacío: '+file);
}
fs.writeFileSync(path.join(__dirname,'interfaz.js'),"'use strict';\n// Generated by preparar_interfaz.js. Edit the source HTML/CSS/JS files.\nmodule.exports="+JSON.stringify(content)+';\n');
console.log('Interfaz completa incorporada: inicio, estilos, scripts y configuración.');
